// node scripts/test-tax.js — ตัวอย่างจาก prompt ต้องผ่านทุกข้อก่อน deploy
require('../rules.js'); const {taxCalc} = require('../tax.js');
const R = globalThis.TAX_RULES[2569]; let fail = 0;
const eq = (name, got, want) => { const ok = Math.abs(got - want) < 0.01; if (!ok) fail++; console.log(`${ok ? 'ผ่าน' : 'ไม่ผ่าน'}  ${name}: ได้ ${got} ต้องได้ ${want}`); };

// ตัวอย่าง 1
let r = taxCalc({inc: 360000, wage: 360000, gpf: 10800}, R);
eq('ตัวอย่าง 1 เงินได้สุทธิ', r.net, 189200); eq('ตัวอย่าง 1 ภาษี', r.tax, 1960);
// ตัวอย่าง 2
r = taxCalc({inc: 600000, wage: 600000, gpf: 60000, v: {life: 20000}}, R);
eq('ตัวอย่าง 2 เงินได้สุทธิ', r.net, 360000); eq('ตัวอย่าง 2 ภาษี', r.tax, 13500);
// กลุ่มเกษียณเกิน 500,000: กบข. 300,000 (30% ของ 1,000,000) + RMF 300,000 → ใช้ได้ 500,000
r = taxCalc({inc: 1000000, wage: 1000000, gpf: 300000, v: {rmf: 300000}}, R);
eq('กลุ่มเกษียณตัดที่ 500,000', r.retUsed, 500000); eq('สิทธิ์เกษียณเหลือ', r.retRoom, 0);
// ประกันชีวิต 90,000 + สุขภาพ 25,000 → รวมได้ 100,000
r = taxCalc({inc: 600000, v: {life: 90000, health: 25000}}, R);
eq('ประกันชีวิต+สุขภาพ ไม่เกิน 100,000', r.ded - 60000, 100000);
// บริจาคการศึกษา 2 เท่า: 600,000 − 100,000 − 60,000 = 440,000 · บริจาค 10,000 → หัก 20,000 (ไม่ถึง 44,000)
r = taxCalc({inc: 600000, v: {donEdu: 10000}}, R);
eq('บริจาค 2 เท่า', r.net, 420000);
// บริจาคการศึกษาเกินเพดาน: 30,000 × 2 = 60,000 > 44,000 → หัก 44,000
r = taxCalc({inc: 600000, v: {donEdu: 30000}}, R);
eq('บริจาค 2 เท่า ชนเพดาน 10%', r.net, 396000);
// เงินได้สุทธิไม่ถึง 150,000 → ภาษี 0 และได้คืนเท่าที่ถูกหักไว้
r = taxCalc({inc: 240000, gpf: 7200, wht: 500}, R);
eq('เงินได้สุทธิไม่ถึง 150,000 ภาษี', r.tax, 0); eq('ได้คืนเท่าที่ถูกหัก', r.diff, 500);
// บิดามารดาเกิน 4 คน → นับ 4
r = taxCalc({inc: 600000, v: {parent: 6}}, R);
eq('บิดามารดาไม่เกิน 4 คน', r.ded - 60000, 120000);

// Thai ESG + Thai ESGX ใช้วงเงินร่วมกัน: เงินได้ 1,200,000 → เพดาน 300,000 · ESG 200,000 + ESGX 200,000 → ใช้ได้รวม 300,000
r = taxCalc({inc: 1200000, v: {esg: 200000, esgx: 200000}}, R);
eq('Thai ESG + ESGX รวมไม่เกิน 300,000', r.ded - 60000, 300000); eq('สิทธิ์ ESG เหลือ', r.esgRoom, 0);
// เพดาน 30% ของเงินได้: เงินได้ 400,000 → 120,000 · ESG 100,000 + ESGX 50,000 → ใช้ได้ 120,000
r = taxCalc({inc: 400000, v: {esg: 100000, esgx: 50000}}, R);
eq('Thai ESG + ESGX ไม่เกิน 30% ของเงินได้', r.ded - 60000, 120000);

console.log(fail ? `\nไม่ผ่าน ${fail} ข้อ` : '\nผ่านทุกข้อ'); process.exit(fail ? 1 : 0);
